import type { Split } from "./dataset";
import { type Outcome, pct, type SplitSummary, type Summary } from "./score";

const cell = (text: string) => text.replaceAll("|", "\\|");

function splitRow(name: string, s: SplitSummary): string {
  return `| ${name} | ${s.n} | ${pct(s.verdict)} | ${pct(s.kind)} | ${pct(s.bagel)} | ${pct(s.spread)} | ${pct(s.toppings)} | ${pct(s.sandwich)} |`;
}

export function describeFailure(o: Outcome): string {
  const parts: string[] = [];
  if (!o.kindCorrect) parts.push(`kind ${o.kind} (want ${o.expectedKind})`);
  if (o.declined) parts.push("declined");
  for (const [id, f] of Object.entries(o.fields)) {
    if (f && !f.correct)
      parts.push(`${id} ${f.got} ${f.p.toFixed(2)} (want ${f.expected.join("/")})`);
  }
  if (o.sandwichCorrect === false && o.sandwich) {
    parts.push(`sandwich ${o.sandwich.p.toFixed(2)} (want ${String(o.sandwich.expected)})`);
  }
  const verdict = o.verdict ?? (o.declined ? "declined" : `out of scope: ${o.kind}`);
  const want = o.expectedVerdicts?.join("/") ?? `out of scope: ${o.expectedKind}`;
  return `${o.order}: ${verdict}, want ${want}${parts.length ? `. ${parts.join("; ")}` : ""}`;
}

function failures(outcomes: readonly Outcome[], split: Split): string {
  const wrong = outcomes.filter((o) => o.split === split && !o.correct);
  if (wrong.length === 0) return "None.\n";
  return `${wrong.map((o) => `- ${cell(describeFailure(o))}`).join("\n")}\n`;
}

function fieldMisses(outcomes: readonly Outcome[], split: Split): string {
  const misses = outcomes.filter(
    (o) =>
      o.split === split &&
      o.correct &&
      (Object.values(o.fields).some((f) => f && !f.correct) || o.sandwichCorrect === false),
  );
  if (misses.length === 0) return "None.\n";
  return `${misses.map((o) => `- ${cell(describeFailure(o))}`).join("\n")}\n`;
}

export function renderReport(summary: Summary, outcomes: readonly Outcome[]): string {
  const s = summary.splits;
  return `# Eval report: question set v${summary.questionSetVersion}

Model \`${summary.model}\`, ${summary.datasetSize} items, ${summary.missing} missing. Generated by \`pnpm eval\`; do not edit by hand.

A verdict is right when the app's own ruling (\`toPolicyResult\`) matches a verdict the labels allow. Field columns score each question on bagel orders only.

| Split | n | Verdict | Input kind | Bagel | Cream cheese | Toppings | Sandwich |
|---|---|---|---|---|---|---|---|
${splitRow("canon", s.canon)}
${splitRow("tune", s.tune)}
${splitRow("holdout", s.holdout)}
${splitRow("all", s.all)}

## Sandwich threshold sweep

Verdict accuracy if \`THRESHOLDS.sandwich\` were each value. Holdout is left out on purpose.

| Threshold | Tune | Canon |
|---|---|---|
${summary.sandwichSweep.map((r) => `| ${r.threshold} | ${pct(r.tune)} | ${pct(r.canon)} |`).join("\n")}

## Abuse guard

${summary.declines} of ${outcomes.length} items declined (none of them are abusive probes). Highest \`is_abusive\`: ${summary.maxAbusive?.toFixed(2) ?? "n/a"}.

## Cost

${summary.avgInputTokens ?? "n/a"} input tokens per call, p50 ${summary.p50LatencyMs ?? "n/a"} ms, about $${summary.costPerPassUsd ?? "n/a"} per full pass.

## Canon failures

${failures(outcomes, "canon")}
## Tune failures

${failures(outcomes, "tune")}
## Right verdict, wrong field (tune)

${fieldMisses(outcomes, "tune")}
<details>
<summary>Holdout failures (check once per finished candidate, never tune against them)</summary>

${failures(outcomes, "holdout")}
</details>
`;
}
